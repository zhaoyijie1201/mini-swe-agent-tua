#!/usr/bin/env python3
"""Generate the complete mini-swe-agent config files for every experiment configuration.

Each output file is self-contained (the `mini` CLI replaces its default config when `-c` is given), so
`B*` files equal `mini.yaml` plus the model pin, and `A*`/`H` files add the TuaAgent switches on top.

    python tua/scripts/gen_configs.py            # writes tua/configs/*.yaml
"""

import copy
from pathlib import Path

import yaml

from minisweagent.config import builtin_config_dir
from minisweagent.utils.serialize import recursive_merge

OUT_DIR = Path(__file__).resolve().parent.parent / "configs"
BASE = yaml.safe_load((builtin_config_dir / "tua" / "base.yaml").read_text())
PROMPT = yaml.safe_load((builtin_config_dir / "tua" / "prompt_tua.yaml").read_text())

FORMAT_ERROR_RECOVERY = """\
{% if finish_reason is defined and (finish_reason == "length" or (finish_reason == "tool_calls" and not has_tool_calls)) -%}
Your previous response reached the output token limit (finish_reason={{ finish_reason }}) before you produced a tool call, so it was cut off. Respond more concisely and finish with exactly one bash tool call. If you need to think more, do so briefly.
{%- else -%}
Your last response contained no valid bash tool call, so nothing was executed.

<error>
{{error}}
</error>

- If you believe the task is complete and verified: issue the submit command `echo COMPLETE_TASK_AND_SUBMIT_FINAL_OUTPUT` as a bash tool call, alone.
- Otherwise keep working: every response must contain at least one bash tool call with arguments {"command": "..."}.
- Nobody can answer questions here; decide using the task statement and what you can observe.
{%- endif %}
"""

AGENT_CLASS = {"agent": {"agent_class": "minisweagent.agents.tua.TuaAgent"}}
SWITCHES = {
    "C1": {"agent": {"budget_notices": True, "step_limit": 150, "wall_time_limit_seconds": 2200}},
    "C2": {
        "agent": {"stall_detection": True, "max_consecutive_format_errors": 10},
        "environment": {"timeout": 120},
        "model": {"format_error_template": FORMAT_ERROR_RECOVERY},
    },
    "C3": {"agent": {"verify_gate": True}},
    "C4": {"agent": {"observation_hygiene": True}},
    "C5": PROMPT,
}
MODELS = {
    "qwen": {
        "model": {
            "model_name": "openrouter/qwen/qwen3.7-flash",
            "model_kwargs": {
                "drop_params": True,
                "extra_body": {
                    "provider": {"order": ["Alibaba"], "allow_fallbacks": False},
                    "reasoning": {"enabled": False},
                },
            },
        }
    },
    "dsflash": {
        "model": {
            "model_name": "openrouter/deepseek/deepseek-v4.1-flash-1017",
            "model_kwargs": {
                "drop_params": True,
                "extra_body": {"provider": {"order": ["DeepSeek"], "allow_fallbacks": False}},
            },
        }
    },
}
# name -> (switches, models). B0/B1 = unmodified harness (no agent_class). A0 = fork with all switches off.
CONFIGS = {
    "B0": ([], ["qwen"]),
    "B1": ([], ["dsflash"]),
    "A0": (["none"], ["qwen"]),
    "A1": (["C1"], ["qwen"]),
    "A2": (["C2"], ["qwen"]),
    "A3": (["C3"], ["qwen"]),
    "A4": (["C4"], ["qwen"]),
    "A5": (["C5"], ["qwen"]),
    "H": (["C1", "C2", "C3", "C4", "C5"], ["qwen", "dsflash"]),
}


def build(switches: list[str], model: str) -> dict:
    parts = [copy.deepcopy(BASE)]
    if switches:
        parts.append(AGENT_CLASS)
    parts += [SWITCHES[s] for s in switches if s != "none"]
    parts.append(MODELS[model])
    return recursive_merge(*parts)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, (switches, models) in CONFIGS.items():
        for model in models:
            path = OUT_DIR / f"{name}-{model}.yaml"
            header = f"# Generated by tua/scripts/gen_configs.py. Configuration {name}: switches={switches or 'none (unmodified harness)'}, model={model}\n"
            path.write_text(
                header + yaml.safe_dump(build(switches, model), sort_keys=False, allow_unicode=True, width=10_000)
            )
            print("wrote", path)


if __name__ == "__main__":
    main()
